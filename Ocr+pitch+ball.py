def padded_box(b, frac, W, H):
    x1, y1, x2, y2 = b
    pw, ph = (x2 - x1) * frac, (y2 - y1) * frac
    return max(0, x1 - pw), max(0, y1 - ph), min(W, x2 + pw), min(H, y2 + ph)

