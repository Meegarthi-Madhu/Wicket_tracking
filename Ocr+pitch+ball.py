def box_iou(a, b):
    ix1, iy1 = max(a[0], b[0]), max(a[1], b[1])
    ix2, iy2 = min(a[2], b[2]), min(a[3], b[3])
    inter = max(0.0, ix2 - ix1) * max(0.0, iy2 - iy1)
    union = (a[2] - a[0]) * (a[3] - a[1]) + (b[2] - b[0]) * (b[3] - b[1]) - inter
    return inter / union if union > 0 else 0.0

def pick_best_pitch(res):
    """Highest-confidence pitch box of one frame -> (x1, y1, x2, y2, conf) or None."""
    if res.boxes is None or len(res.boxes) == 0:
        return None
    conf = res.boxes.conf.cpu().numpy()
    i = int(conf.argmax())
    x1, y1, x2, y2 = res.boxes.xyxy[i].cpu().numpy().tolist()
    return (x1, y1, x2, y2, float(conf[i]))

def smooth_box(prev, new, w_new):
    """Exponential smoothing of the pitch box to reduce frame-to-frame jitter."""
    if prev is None or box_iou(prev[:4], new[:4]) < 0.3:
        return new
    sm = tuple(w_new * n + (1 - w_new) * p for p, n in zip(prev[:4], new[:4]))
    return sm + (new[4],)

